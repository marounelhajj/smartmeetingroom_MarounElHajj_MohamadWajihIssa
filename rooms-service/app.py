"""
Rooms Service - Smart Meeting Room System
Author: Maroun El Hajj

This microservice manages:
- meeting rooms (name, capacity, equipment, location)
- room availability (basic flag)
- search / filter API

Authentication:
- expects JWT in Authorization header, generated by Users Service
- only admins and facility managers can create/update/delete rooms
"""

from flask import Flask, request, jsonify
from flask_sqlalchemy import SQLAlchemy
from functools import wraps
from typing import Optional
import datetime
import os
import jwt

app = Flask(__name__)

app.config["SQLALCHEMY_DATABASE_URI"] = os.getenv(
    "DATABASE_URL", "sqlite:///rooms.db"
)
app.config["SQLALCHEMY_TRACK_MODIFICATIONS"] = False
app.config["SECRET_KEY"] = os.getenv(
    "SECRET_KEY", "change-this-secret-key-in-production"
)

db = SQLAlchemy(app)

# ----------------------------------------------------------------------
# Models
# ----------------------------------------------------------------------


class Room(db.Model):
    """DB model for meeting rooms."""

    __tablename__ = "rooms"

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(80), unique=True, nullable=False, index=True)
    capacity = db.Column(db.Integer, nullable=False)
    equipment = db.Column(db.String(255), nullable=True)  # comma-separated list
    location = db.Column(db.String(120), nullable=False)
    is_available = db.Column(db.Boolean, default=True)
    created_at = db.Column(db.DateTime, default=datetime.datetime.utcnow)

    def to_dict(self):
        return {
            "id": self.id,
            "name": self.name,
            "capacity": self.capacity,
            "equipment": self.equipment,
            "location": self.location,
            "is_available": self.is_available,
            "created_at": self.created_at.isoformat(),
        }


# ----------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------


def sanitize(text: Optional[str]) -> Optional[str]:
    if text is None:
        return None
    bad = ["<", ">", '"', "'", ";", "--", "/*", "*/"]
    out = str(text)
    for b in bad:
        out = out.replace(b, "")
    return out.strip()


def decode_token(auth_header: str):
    if auth_header.startswith("Bearer "):
        token = auth_header[7:]
    else:
        token = auth_header
    return jwt.decode(token, app.config["SECRET_KEY"], algorithms=["HS256"])


def auth_required(fn):
    """All routes (except /health, GET /api/rooms) require a valid token."""

    @wraps(fn)
    def wrapper(*args, **kwargs):
        header = request.headers.get("Authorization")
        if not header:
            return jsonify({"error": "Authorization header missing"}), 401
        try:
            payload = decode_token(header)
        except jwt.ExpiredSignatureError:
            return jsonify({"error": "Token expired"}), 401
        except jwt.InvalidTokenError:
            return jsonify({"error": "Invalid token"}), 401

        return fn(payload, *args, **kwargs)

    return wrapper


def admin_or_facility_required(fn):
    """Decorator: only admins or facility managers."""

    @wraps(fn)
    def wrapper(payload, *args, **kwargs):
        role = payload.get("role")
        if role not in ["admin", "facility_manager"]:
            return jsonify({"error": "Admin or facility manager role required"}), 403
        return fn(payload, *args, **kwargs)

    return wrapper


