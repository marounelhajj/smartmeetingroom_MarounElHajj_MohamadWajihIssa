@app.route("/api/bookings", methods=["GET"])
@auth_required
def list_bookings(payload: dict):
    """
    List bookings.

    - Admin / facility_manager / auditor: all bookings
    - Others: only own bookings
    """
    if can_manage_all(payload.get("role", "")):
        bookings = Booking.query.order_by(Booking.start_time.desc()).all()
    else:
        bookings = (
            Booking.query.filter_by(user_id=payload.get("user_id"))
            .order_by(Booking.start_time.desc())
            .all()
        )
    return jsonify({"bookings": [b.to_dict() for b in bookings], "count": len(bookings)}), 200


@app.route("/api/bookings/history/<int:user_id>", methods=["GET"])
@auth_required
def booking_history(payload: dict, user_id: int):
    """
    Retrieve booking history for a user.

    - Admin / facility_manager / auditor: any user
    - Regular users: only their own history
    """
    if not can_manage_all(payload.get("role", "")) and payload.get("user_id") != user_id:
        return jsonify({"error": "Insufficient permissions"}), 403

    cached = _cache_get(_history_cache, user_id)
    if cached is not None:
        return jsonify({"bookings": cached, "count": len(cached)}), 200

    bookings = (
        Booking.query.filter_by(user_id=user_id)
        .order_by(Booking.start_time.desc())
        .all()
    )
    serialized = [b.to_dict() for b in bookings]
    _cache_set(_history_cache, user_id, serialized)
    return jsonify({"bookings": serialized, "count": len(serialized)}), 200


@app.route("/api/bookings/check", methods=["GET"])
def check_availability():
    """
    Check if a room is available for a given time range.

    Query params: room_id, start_time, end_time (ISO format).
    """
    room_id = request.args.get("room_id")
    start_raw = request.args.get("start_time")
    end_raw = request.args.get("end_time")

    if not room_id or not start_raw or not end_raw:
        return jsonify({"error": "room_id, start_time and end_time are required"}), 400

    try:
        room_id_int = int(room_id)
    except ValueError:
        return jsonify({"error": "room_id must be an integer"}), 400

    start_time, err = parse_datetime(start_raw)
    if err:
        return jsonify({"error": err}), 400
    end_time, err = parse_datetime(end_raw)
    if err:
        return jsonify({"error": err}), 400

    if end_time <= start_time:
        return jsonify({"error": "end_time must be after start_time"}), 400

    cache_key = (room_id_int, start_time.isoformat(), end_time.isoformat())
    cached = _cache_get(_availability_cache, cache_key)
    if cached is not None:
        return jsonify(cached), 200

    conflicts = _check_conflict(room_id_int, start_time, end_time)
    result = {
        "room_id": room_id_int,
        "available": len(conflicts) == 0,
        "conflicts": [c.to_dict() for c in conflicts],
    }
    _cache_set(_availability_cache, cache_key, result)
    return (
        jsonify(
            result
        ),
        200,
    )


@app.route("/api/bookings", methods=["POST"])
@auth_required
def create_booking(payload: dict):
    """
    Create a booking.

    JSON body:
    {
        "room_id": 1,
        "room_name": "Conference Room",
        "start_time": "2025-01-01T10:00",
        "end_time": "2025-01-01T11:00",
        "user_id": 5,          # optional, admin/facility only
        "username": "alice"    # optional, admin/facility only
    }
    """
    data = request.get_json() or {}

    for field in ["room_id", "start_time", "end_time"]:
        if not data.get(field):
            return jsonify({"error": f"{field} is required"}), 400

    try:
        room_id = int(data["room_id"])
    except (TypeError, ValueError):
        return jsonify({"error": "room_id must be an integer"}), 400

    start_time, err = parse_datetime(data.get("start_time"))
    if err:
        return jsonify({"error": err}), 400

    end_time, err = parse_datetime(data.get("end_time"))
    if err:
        return jsonify({"error": err}), 400

    if end_time <= start_time:
        return jsonify({"error": "end_time must be after start_time"}), 400

    now = datetime.datetime.utcnow()
    if start_time < now:
        return jsonify({"error": "Bookings must start in the future"}), 400

    target_user_id = payload.get("user_id")
    target_username = payload.get("username", "unknown")
    if can_manage_all(payload.get("role", "")):
        # Admin / facility manager can book on behalf of others
        target_user_id = data.get("user_id", target_user_id)
        target_username = sanitize(data.get("username", target_username)) or target_username

    if not target_user_id:
        return jsonify({"error": "user_id missing in token"}), 400

    conflicts = _check_conflict(room_id, start_time, end_time)
    if conflicts:
        return (
            jsonify(
                {
                    "error": "Room already booked in requested time window",
                    "conflicts": [c.to_dict() for c in conflicts],
                }
            ),
            409,
        )

    booking = Booking(
        user_id=int(target_user_id),
        username=target_username,
        room_id=room_id,
        room_name=sanitize(data.get("room_name")),
        start_time=start_time,
        end_time=end_time,
        status="booked",
    )

    try:
        db.session.add(booking)
        db.session.commit()
        _invalidate_caches_for_room(room_id)
        _invalidate_history_for_user(int(target_user_id))
        return jsonify({"message": "Booking created", "booking": booking.to_dict()}), 201
    except Exception as exc:  # noqa: BLE001
        db.session.rollback()
        return jsonify({"error": f"Failed to create booking: {exc}"}), 500


@app.route("/api/bookings/<int:booking_id>", methods=["PUT"])
@auth_required
def update_booking(payload: dict, booking_id: int):
    """
    Update a booking time or room.

    - Owners can update their booking
    - Admin / facility_manager can update any booking
    """
    booking = Booking.query.get(booking_id)
    if not booking:
        return jsonify({"error": "Booking not found"}), 404
    old_room_id = booking.room_id

    role = payload.get("role")
    if not can_manage_all(role) and booking.user_id != payload.get("user_id"):
        return jsonify({"error": "Insufficient permissions"}), 403

    data = request.get_json() or {}

    if "room_id" in data:
        try:
            booking.room_id = int(data["room_id"])
        except (TypeError, ValueError):
            return jsonify({"error": "room_id must be an integer"}), 400

    if "room_name" in data:
        booking.room_name = sanitize(data.get("room_name"))

    if "start_time" in data:
        start_time, err = parse_datetime(data.get("start_time"))
        if err:
            return jsonify({"error": err}), 400
        booking.start_time = start_time

    if "end_time" in data:
        end_time, err = parse_datetime(data.get("end_time"))
        if err:
            return jsonify({"error": err}), 400
        booking.end_time = end_time

    if booking.end_time <= booking.start_time:
        return jsonify({"error": "end_time must be after start_time"}), 400

    conflicts = _check_conflict(
        booking.room_id, booking.start_time, booking.end_time, exclude_booking_id=booking.id
    )
    if conflicts:
        return (
            jsonify(
                {
                    "error": "Room already booked in requested time window",
                    "conflicts": [c.to_dict() for c in conflicts],
                }
            ),
            409,
        )

    try:
        db.session.commit()
        _invalidate_caches_for_room(booking.room_id)
        if old_room_id != booking.room_id:
            _invalidate_caches_for_room(old_room_id)
        _invalidate_history_for_user(booking.user_id)
        return jsonify({"message": "Booking updated", "booking": booking.to_dict()}), 200
    except Exception as exc:  # noqa: BLE001
        db.session.rollback()
        return jsonify({"error": f"Failed to update booking: {exc}"}), 500


@app.route("/api/bookings/<int:booking_id>", methods=["DELETE"])
@auth_required
def cancel_booking(payload: dict, booking_id: int):
    """
    Cancel a booking (soft delete).
    """
    booking = Booking.query.get(booking_id)
    if not booking:
        return jsonify({"error": "Booking not found"}), 404

    role = payload.get("role")
    if not can_manage_all(role) and booking.user_id != payload.get("user_id"):
        return jsonify({"error": "Insufficient permissions"}), 403

    booking.status = "cancelled"
    try:
        db.session.commit()
        _invalidate_caches_for_room(booking.room_id)
        _invalidate_history_for_user(booking.user_id)
        return jsonify({"message": "Booking cancelled", "booking": booking.to_dict()}), 200
    except Exception as exc:  # noqa: BLE001
        db.session.rollback()
        return jsonify({"error": f"Failed to cancel booking: {exc}"}), 500


