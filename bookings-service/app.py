# ----------------------------------------------------------------------
# Auditing & rate limiting setup
# ----------------------------------------------------------------------

RATE_LIMIT_REQUESTS = int(os.getenv("RATE_LIMIT_REQUESTS", "60"))  # requests
RATE_LIMIT_WINDOW = int(os.getenv("RATE_LIMIT_WINDOW", "60"))  # seconds
_rate_buckets: dict = {}


def _init_logging():
    """Configure rotating file logging for auditing."""
    os.makedirs("logs", exist_ok=True)
    handler = RotatingFileHandler("logs/bookings.log", maxBytes=500_000, backupCount=3)
    formatter = logging.Formatter(
        "%(asctime)s %(levelname)s %(message)s"
    )
    handler.setFormatter(formatter)
    app.logger.setLevel(logging.INFO)
    app.logger.addHandler(handler)


_init_logging()

# ----------------------------------------------------------------------
# Caching (simple in-memory with TTL)
# ----------------------------------------------------------------------

BOOKING_CACHE_TTL = int(os.getenv("BOOKING_CACHE_TTL", "60"))
_availability_cache: dict = {}
_history_cache: dict = {}


def _cache_get(cache: dict, key):
    entry = cache.get(key)
    if not entry:
        return None
    expires, value = entry
    if time.time() > expires:
        cache.pop(key, None)
        return None
    return value


def _cache_set(cache: dict, key, value):
    cache[key] = (time.time() + BOOKING_CACHE_TTL, value)


def _invalidate_caches_for_room(room_id: int):
    """Clear availability cache entries touching a room."""
    to_delete = [k for k in _availability_cache if k[0] == room_id]
    for k in to_delete:
        _availability_cache.pop(k, None)


def _invalidate_history_for_user(user_id: int):
    _history_cache.pop(user_id, None)

