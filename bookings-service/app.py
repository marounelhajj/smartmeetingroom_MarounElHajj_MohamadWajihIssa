class Booking(db.Model):
    """SQLAlchemy model representing a room booking."""

    __tablename__ = "bookings"
    __table_args__ = (
        db.Index("ix_booking_room_time", "room_id", "start_time", "end_time"),
    )

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, nullable=False, index=True)
    username = db.Column(db.String(80), nullable=False)
    room_id = db.Column(db.Integer, nullable=False, index=True)
    room_name = db.Column(db.String(120), nullable=True)
    start_time = db.Column(db.DateTime, nullable=False)
    end_time = db.Column(db.DateTime, nullable=False)
    status = db.Column(db.String(20), default="booked")  # booked | cancelled
    created_at = db.Column(db.DateTime, default=datetime.datetime.utcnow)
    updated_at = db.Column(
        db.DateTime,
        default=datetime.datetime.utcnow,
        onupdate=datetime.datetime.utcnow,
    )

    def to_dict(self) -> dict:
        """Serialize booking for responses."""
        return {
            "id": self.id,
            "user_id": self.user_id,
            "username": self.username,
            "room_id": self.room_id,
            "room_name": self.room_name,
            "start_time": self.start_time.isoformat(),
            "end_time": self.end_time.isoformat(),
            "status": self.status,
            "created_at": self.created_at.isoformat(),
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
        }


