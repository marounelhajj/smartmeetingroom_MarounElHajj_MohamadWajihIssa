def sanitize(text: Optional[str]) -> Optional[str]:
    """Remove obvious SQL/script characters."""
    if text is None:
        return None
    bad = ["<", ">", '"', "'", ";", "--", "/*", "*/"]
    cleaned = str(text)
    for b in bad:
        cleaned = cleaned.replace(b, "")
    return cleaned.strip()


def decode_token(auth_header: str) -> dict:
    """Decode JWT from Authorization header."""
    if auth_header.startswith("Bearer "):
        token = auth_header[7:]
    else:
        token = auth_header
    return jwt.decode(token, app.config["SECRET_KEY"], algorithms=["HS256"])


def _try_decode_for_logging() -> dict:
    """Decode token if present; used for auditing; ignores errors."""
    header = request.headers.get("Authorization")
    if not header:
        return {}
    try:
        return decode_token(header)
    except Exception:  # noqa: BLE001
        return {}


def parse_datetime(value: Optional[str]) -> Tuple[Optional[datetime.datetime], Optional[str]]:
    """Parse ISO datetime string safely."""
    if not value:
        return None, "Datetime value missing"
    try:
        return datetime.datetime.fromisoformat(value), None
    except ValueError:
        return None, "Datetime must be ISO 8601 format (YYYY-MM-DDTHH:MM)"


def auth_required(fn):
    """Require valid JWT on the request."""

    @wraps(fn)
    def wrapper(*args, **kwargs):
        header = request.headers.get("Authorization")
        if not header:
            return jsonify({"error": "Authorization header missing"}), 401
        try:
            payload = decode_token(header)
        except jwt.ExpiredSignatureError:
            return jsonify({"error": "Token expired"}), 401
        except jwt.InvalidTokenError:
            return jsonify({"error": "Invalid token"}), 401
        return fn(payload, *args, **kwargs)

    return wrapper


def _prune_bucket(bucket: List[float], now: float) -> List[float]:
    """Remove timestamps outside the window."""
    return [ts for ts in bucket if now - ts <= RATE_LIMIT_WINDOW]


@app.before_request
def enforce_rate_limit():
    """Simple sliding-window rate limiter per IP + endpoint."""
    if request.endpoint == "health":
        return
    now = time.time()
    key = f"{request.remote_addr}:{request.endpoint}"
    bucket = _rate_buckets.get(key, [])
    bucket = _prune_bucket(bucket, now)
    if len(bucket) >= RATE_LIMIT_REQUESTS:
        return jsonify({"error": "Rate limit exceeded"}), 429
    bucket.append(now)
    _rate_buckets[key] = bucket


@app.after_request
def audit_log(response):
    """Log basic request/response data for auditing."""
    payload = _try_decode_for_logging()
    app.logger.info(
        "user_id=%s role=%s method=%s path=%s status=%s",
        payload.get("user_id"),
        payload.get("role"),
        request.method,
        request.path,
        response.status_code,
    )
    return response


def can_manage_all(role: str) -> bool:
    """Return True if role can manage all bookings."""
    return role in ["admin", "facility_manager", "auditor"]


def _check_conflict(room_id: int, start_time: datetime.datetime, end_time: datetime.datetime, exclude_booking_id: Optional[int] = None) -> List[Booking]:
    """Return bookings that conflict with given time window for a room."""
    query = Booking.query.filter(
        Booking.room_id == room_id,
        Booking.status == "booked",
        Booking.start_time < end_time,
        Booking.end_time > start_time,
    )
    if exclude_booking_id:
        query = query.filter(Booking.id != exclude_booking_id)
    return query.all()


